let currentLang = localStorage.getItem('strawhats_lang') || 'en';

function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('strawhats_lang', lang);

  // Update HTML lang attribute and body class for font switching
  document.documentElement.lang = lang;
  if (lang === 'bn') {
    document.body.classList.add('lang-bn');
  } else {
    document.body.classList.remove('lang-bn');
  }

  // Update all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Update Language toggle button label
  const langBtnText = document.getElementById('lang-btn-text');
  if (langBtnText) {
    langBtnText.textContent = translations[lang].lang_btn_text;
  }
  const mobileLangBtnText = document.getElementById('mobile-lang-btn-text');
  if (mobileLangBtnText) {
    mobileLangBtnText.textContent = translations[lang].mobile_lang_btn_text;
  }

  // Refresh Lucide icons
  if (window.lucide && typeof window.lucide.createIcons === 'function') {
    window.lucide.createIcons();
  }
}

function toggleLanguage() {
  const nextLang = currentLang === 'en' ? 'bn' : 'en';
  setLanguage(nextLang);
}

// Attach listener on DOMContentLoaded
document.addEventListener('DOMContentLoaded', () => {
  // Initialize with stored or default language
  setLanguage(currentLang);

  const langBtn = document.getElementById('lang-toggle-btn');
  if (langBtn) {
    langBtn.addEventListener('click', toggleLanguage);
  }

  const mobileLangBtn = document.getElementById('mobile-lang-toggle-btn');
  if (mobileLangBtn) {
    mobileLangBtn.addEventListener('click', toggleLanguage);
  }
});
